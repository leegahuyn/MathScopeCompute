"""Compile the exact generated source bytes with the GitHub pinned Lean toolchain."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import time


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lean", required=True, type=Path)
    parser.add_argument("--repo", required=True, type=Path)
    parser.add_argument("--imports", required=True, type=Path)
    parser.add_argument("--jobs", required=True, type=Path)
    args = parser.parse_args()
    version = subprocess.check_output([str(args.lean), "--version"], text=True)
    expected = "5045d0056413266e57c625dcd7c365b10e377c52"
    if expected not in version or not os.getenv("GITHUB_RUN_ID"):
        raise RuntimeError("Pinned GitHub Lean execution is required")
    directory = args.jobs.resolve()
    manifest = json.loads((directory / "generated.json").read_bytes())["manifest"]
    receipt = {
        "sourceCommit": subprocess.check_output(
            ["git", "-C", str(args.repo), "rev-parse", "HEAD"], text=True).strip(),
        "githubRun": os.environ["GITHUB_RUN_ID"],
        "leanCommit": expected, "leanVersion": version.strip(),
        "leanSHA256": digest(args.lean.read_bytes()), "mathlibUsed": False, "cases": {},
    }
    for name, row in manifest.items():
        source = (directory / row["file"]).read_bytes()
        if digest(source) != row["sourceSHA256"]:
            raise ValueError(f"Generated bytes changed in {name}")
        start = time.monotonic_ns()
        run = subprocess.run(
            [str(args.lean), "--memory=1536", "--threads=1", row["file"]],
            cwd=directory, env={**os.environ, "LEAN_PATH": str(args.imports.resolve())},
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, check=False, timeout=60)
        elapsed_ms = (time.monotonic_ns() - start) // 1_000_000
        log = name + ".log"
        (directory / log).write_bytes(run.stdout)
        content = run.stdout.decode("utf-8")
        target = re.escape(row["target"])
        type_match = re.search(r"(?m)^" + target + r"\s*:\s*(.*?)(?=\n'|\Z)", content, flags=re.S)
        dependencies = re.search(r"(?m)^'" + target + r"' depends on axioms: \[(.*?)\]$", content)
        axioms = [] if dependencies is None else dependencies.group(1).split(", ")
        warnings = [line for line in content.splitlines() if "warning:" in line]
        sorry = "sorryAx" in content or "declaration uses 'sorry'" in content
        receipt["cases"][name] = {
            "jobId": row["jobId"], "sourceSHA256": digest(source),
            "log": log, "logSHA256": digest(run.stdout), "exitCode": run.returncode,
            "elapsedMilliseconds": elapsed_ms, "target": row["target"],
            "targetType": " ".join(type_match.group(1).split()) if type_match else None,
            "axioms": axioms, "warnings": warnings, "usesSorry": sorry,
        }
        (directory / "compiler-receipt.json").write_text(json.dumps(receipt, indent=2) + "\n")
        if (run.returncode != 0 or not type_match or warnings or sorry
                or set(axioms) - {"propext", "Classical.choice", "Quot.sound"}
                or dependencies is None and f"'{row['target']}' does not depend on any axioms" not in content):
            raise RuntimeError(f"Unexpected generated Lean audit in {name}\n{content}")
        print(name, run.returncode, elapsed_ms, "ms", flush=True)


if __name__ == "__main__":
    main()
