    client=read(ROOT/'browser-client.js').replace('__P8_STATIC_WORKER_SOURCE__',json.dumps(worker,ensure_ascii=False)).replace('</script','<\\/script')
    outputs={WEB/'p8-engine.bundle.js':client,ROOT/'build-data.json':json.dumps(build,ensure_ascii=False,indent=2)+'\n'}
    for path,content in outputs.items():
        if args.check:
            if not path.exists() or read(path)!=content:raise ValueError('Generated build stale: '+str(path))
        else:path.write_text(content,encoding='utf-8',newline='\n')
    subprocess.run(['node','--check',str(WEB/'p8-engine.bundle.js')],check=True)
    print(json.dumps({'sourceFiles':len(files),'manifestSHA256':source['manifestSHA256'],'workerBytes':len(worker.encode()),'bundleBytes':len(client.encode()),'leanEvidenceStatus':evidence['status'],'checkOnly':args.check}))
