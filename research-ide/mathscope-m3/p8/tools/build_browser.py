"""Deterministic static module closure; no package installation or user-code evaluation."""
from pathlib import Path
import argparse, hashlib, importlib.util, json, re, subprocess

ROOT=Path(__file__).resolve().parents[1]
RESEARCH=ROOT.parents[1]
WEB=ROOT.parent/'web'
IMPORT=re.compile(r"^import\s+(\{[\s\S]*?\}|\*\s+as\s+\w+)\s+from\s+['\"]([^'\"]+)['\"];?\s*$",re.M)
REEXPORT=re.compile(r"^export\s+(\{[^}]+\}|\*)\s+from\s+['\"]([^'\"]+)['\"];?\s*$",re.M)
def sha(value):return hashlib.sha256(value.encode() if isinstance(value,str) else value).hexdigest()
def canonical(value):return json.dumps(value,ensure_ascii=False,sort_keys=True,separators=(',',':'),allow_nan=False)
def read(path):return path.read_text(encoding='utf-8')
def p8_criteria(original,progress):
    """Retain the exact blueprint text while binding assessed P8 progress."""
    if progress.get('schema')!='MathScope.M3.P8.Progress/1':raise ValueError('Invalid P8 progress schema')
    expected=[c for c in original['criteria'] if c['id'].startswith('P8-')]
    rows=progress.get('criteria',[])
    if [c.get('id') for c in rows]!=[c['id'] for c in expected]:raise ValueError('P8 criteria missing, reordered, or duplicated')
    for row,criterion in zip(rows,expected):
        for key in ['id','title','text','page','source']:
            if row.get(key)!=criterion.get(key):raise ValueError('Original P8 criterion changed: '+criterion['id']+'/'+key)
        if not isinstance(row.get('status'),str) or not row['status'] or type(row.get('originalCriterionComplete')) is not bool:raise ValueError('P8 assessment status is malformed')
        if row['originalCriterionComplete'] and (row['status']!='PASS' or not row.get('evidence')):raise ValueError('Completed P8 criterion needs PASS and concrete evidence')
    return rows
def target(path,value):
    if not value.startswith('.'):raise ValueError('Only static local imports: '+value)
    resolved=(path.parent/value).resolve()
    if not resolved.is_relative_to(RESEARCH) or not resolved.is_file():raise ValueError('Invalid module path: '+str(resolved))
    return resolved
def bundle(entry):
    order=[];visiting=set();done=set()
    def visit(path):
        if path in visiting:raise ValueError('Module cycle: '+str(path))
        if path in done:return
        visiting.add(path);source=read(path)
        if re.search(r'\bimport\s*\(|\bimport\.meta|\beval\s*\(|\bnew\s+Function\b',source):raise ValueError('Dynamic execution is outside this static bundle: '+str(path))
        for pattern in [IMPORT,REEXPORT]:
            for match in pattern.finditer(source):visit(target(path,match.group(2)))
        visiting.remove(path);done.add(path);order.append(path)
    visit(entry.resolve());symbols={path:'__p8_'+str(i) for i,path in enumerate(order)}
    output=['/* Static P8 source closure. Generated by p8/tools/build_browser.py. */','(()=>{','"use strict";']
    for path in order:
        source=read(path);exports=[];stars=[]
        def imports(match):
            fields=match.group(1);dependency=symbols[target(path,match.group(2))]
            return 'const '+(fields.split()[-1] if fields.startswith('*') else re.sub(r'\s+as\s+',': ',fields))+' = '+dependency+';'
        source=IMPORT.sub(imports,source)
        def reexport(match):
            dependency=symbols[target(path,match.group(2))]
            if match.group(1)=='*':stars.append('...'+dependency)
            else:
                for item in match.group(1)[1:-1].split(','):
                    names=re.split(r'\s+as\s+',item.strip());exports.append(names[-1]+':'+dependency+'.'+names[0])
            return ''
        source=REEXPORT.sub(reexport,source)
        exports.extend(re.findall(r'^export\s+(?:async\s+)?(?:function|class|const|let)\s+([\w$]+)',source,re.M))
        def list_export(match):
            for item in match.group(1).split(','):
                names=re.split(r'\s+as\s+',item.strip());exports.append(names[-1]+':'+names[0])
            return ''
        source=re.sub(r'^export\s*\{([^}]+)\}\s*;?\s*$',list_export,source,flags=re.M)
        source=re.sub(r'^export\s+','',source,flags=re.M)
        if re.search(r'^\s*(?:import|export)\s',source,re.M):raise ValueError('Unsupported ESM form: '+str(path))
        output+=['const '+symbols[path]+' = (()=>{',source,'return {'+','.join(stars+list(dict.fromkeys(exports)))+'};','})();']
    output.append('})();')
    return '\n'.join(output),order

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    worker,closure=bundle(ROOT/'worker-entry.mjs')
    extra=[ROOT/'browser-client.js',Path(__file__).resolve(),ROOT.parent/'P7_PROGRESS.json',ROOT.parent/'P8_PROGRESS.json',ROOT.parent/'ORIGINAL_M3_M4_CRITERIA.json',ROOT/'review-fixture-evidence.json',ROOT/'tools/build_review_fixtures.py',ROOT/'tools/audit_conditional_lean.py',ROOT/'tools/audit_p7_mutations.py',ROOT.parent/'cli.py']
