        self.assertEqual(checks["available_producer_definitions"]["evidence"]["verified_count"], 11)
        self.assertEqual(checks["available_producer_definitions"]["evidence"]["missing_unbundled_files"], [])
        self.assertTrue(checks["producer_definitions"]["passed"])
        self.assertTrue(checks["sealed_saved_inputs"]["passed"])
        self.assertTrue(checks["general_fixed_order_source_continuation"]["passed"])
        self.assertTrue(checks["actual_call_graph_and_no_self_premise"]["passed"])
        self.assertTrue(checks["complete_source_leaf_inventory"]["passed"])
        self.assertTrue(checks["own_label_to_reference_scalar_norm"]["passed"])
        self.assertTrue(checks["independent_exact_original_exponent_inclusions"]["passed"])
        self.assertTrue(checks["recovered_parent_native_162_and_nonzero_projection"]["passed"])
        self.assertTrue(checks["gf_conditional_artifact_audit"]["passed"])
        self.assertTrue(checks["all_fixed_order_theorem_audit"]["passed"])
