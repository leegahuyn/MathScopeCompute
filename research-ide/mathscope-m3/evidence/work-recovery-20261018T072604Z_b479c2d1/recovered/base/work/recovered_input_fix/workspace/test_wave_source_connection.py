"""Stdlib checks using unchanged archived inputs, not producer execution.

Expected counts, original rational margins, roots and the unresolved G/F scope
below are independent literal requirements from the source audit. They are not
generated by the implementation's reference builder or its own output.
"""
import copy
import importlib.util
import json
from pathlib import Path
import shutil
import tempfile
import unittest
import zipfile

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("checked_wave_connection", HERE/"wave_source_connection.py")
wave = importlib.util.module_from_spec(spec)
spec.loader.exec_module(wave)


class WaveSourceTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        with zipfile.ZipFile(HERE/"payload/acceptance/inputs/MathScope_M3_WaveNorm_Continuation.zip") as archive:
            cls.program = json.loads(archive.read("MathScope_M3_WaveNorm_Continuation/evidence/WAVE_NORM_PROGRAM.json"))
            cls.initialized = json.loads(archive.read("MathScope_M3_WaveNorm_Continuation/inherited/inherited/inherited/sources/initialized.json"))
        recovery = HERE/"wave_reference/source_recovery"
        cls.native = json.loads((recovery/"NATIVE_DEFINITIONS.json").read_text(encoding="utf-8"))
        ndjson_path = recovery/"TARGET_SOURCE_NODES.ndjson"
        if not ndjson_path.is_file():
            ndjson_path = recovery/"RECOVERED_PARENT_SOURCE_NODES.ndjson"
        cls.nodes = dict(json.loads(line) for line in ndjson_path.read_bytes().splitlines())

    def test_original_B0_exact_margin(self):
        result = wave.exponent_inclusion("99997/100000", "7/10")
        self.assertTrue(result["passed"])
        self.assertEqual(result["margin"], "29997/100000")

    def test_original_C0_exact_margin(self):
        self.assertEqual(wave.exponent_inclusion("99999/50000", "6/5")["margin"], "39999/50000")
        self.assertEqual(wave.exponent_inclusion("149/100", "6/5")["margin"], "29/100")

    def test_class_expression_rational_identity(self):
        self.assertEqual(str(wave.exact_exponent("2-2*kappa_s")), "99999/50000")

    def test_inadequate_exponent_is_rejected(self):
        self.assertFalse(wave.exponent_inclusion("69/100", "7/10")["passed"])

    def test_float_is_not_exact_exponent(self):
        with self.assertRaises(ValueError):
            wave.exact_exponent(0.7)

    def test_eval_or_unknown_expression_rejected(self):
        with self.assertRaises(ValueError):
            wave.exact_exponent("__import__('os')")

    def test_actual_13_call_308_leaf_dag(self):
        result = wave.validate_wave_dag(self.program)
        self.assertEqual(result["call_count"], 13)
        self.assertEqual(result["counts_by_producer"], {"primary":1,"commonY":15,"background":56,"radial":202,"fourier":9,"five":25})

    def test_cycle_rejected(self):
        bad = copy.deepcopy(self.program)
        bad["call_graph"][1]["dependencies"] = [1]
        with self.assertRaises(ValueError):
            wave.validate_wave_dag(bad)

    def test_boolean_call_id_rejected(self):
        bad = copy.deepcopy(self.program)
        bad["call_graph"][1]["id"] = True
        with self.assertRaises(ValueError):
            wave.validate_wave_dag(bad)

    def test_missing_source_call_rejected(self):
        bad = copy.deepcopy(self.program)
        node = next(n for n in bad["scalar_nodes"] if n["op"] == "source_norm_result")
        node["args"][0] = 999
        with self.assertRaises(ValueError):
            wave.validate_wave_dag(bad)

    def test_bad_selector_path_rejected(self):
        bad = copy.deepcopy(self.program)
        node = next(n for n in bad["scalar_nodes"] if n["op"] == "source_norm_result")
        node["args"][1] = [True]
        with self.assertRaises(ValueError):
            wave.validate_wave_dag(bad)

    def test_scalar_forward_reference_rejected(self):
        bad = copy.deepcopy(self.program)
        index = next(i for i,n in enumerate(bad["scalar_nodes"]) if n["op"] == "multiply")
        bad["scalar_nodes"][index]["args"][0] = index
        with self.assertRaises(ValueError):
            wave.validate_wave_dag(bad)

    def test_final_defect_self_premise_rejected(self):
        bad = copy.deepcopy(self.program)
        leaf = next(n for n in bad["scalar_nodes"] if n["op"] == "source_norm_result" and bad["call_graph"][n["args"][0]]["producer"] == "primary")
        leaf["args"][0] = 12
        with self.assertRaisesRegex(ValueError, "own wave premise"):
            wave.validate_wave_dag(bad)

    def test_consumer_derivative_loss_preserved(self):
        bad = copy.deepcopy(self.program)
        bad["rows"][0]["primary_input_orders_used"] = 0
        with self.assertRaises(ValueError):
            wave.validate_wave_dag(bad)

    def test_actual_reference_scalar_factor(self):
        result = wave.validate_reference_norms(self.program)
        self.assertEqual(len(result["rows"]), 12)
        self.assertEqual(result["affine_upper_bound"], 32404)

    def test_envelope_removed_rejected(self):
        bad = copy.deepcopy(self.program)
        bad["rows"][0]["modes"]["1"]["pulse_power"] = 0
        with self.assertRaises(ValueError):
            wave.validate_reference_norms(bad)

    def test_reference_factor_omitted_rejected(self):
        bad = copy.deepcopy(self.program)
        bad["rows"][0]["modes"]["1"]["constant"] = bad["rows"][0]["own_label_modes"]["1"]["constant"]
        with self.assertRaises(ValueError):
            wave.validate_reference_norms(bad)

    def test_actual_native_projection_does_not_claim_GF(self):
        result = wave.validate_finite_projection(self.initialized, self.native, self.nodes)
        self.assertEqual([r["native_rows"] for r in result["native"]], [162,162,162])
        self.assertEqual(len(result["projection"]), 10)
        self.assertIn("no G_wave/F_pulse", result["scope"])

