/** Complete original global angular-mean covariance on one common torus.
 *
 * Every one of the 81 point candidates and both original signs is retained
 * under the same periodic indexed operation. Radial integration keeps that
 * complete operation, so all cells crossed by an integral remain present.
 * The pressure therefore retains every auxiliary Fourier mode, not just
 * the previously constructed normalized Haar mean.
 */
