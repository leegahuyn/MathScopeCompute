"""Build the small browser view of an observed source-constructor execution.

This command checks the saved execution, artifacts and every captured source
byte. It does not execute the source constructor or enlarge its mathematical
scope. The expensive constructor remains a separate, explicit manual gate.
"""
from pathlib import Path
import argparse
import hashlib
import json

ROOT = Path(__file__).resolve().parents[4]
OUT = Path(__file__).resolve().parents[1]
RECEIPT = OUT / 'evidence/source-current-20261012/source-current-execution.json'
TARGET = OUT / 'source-current-evidence.mjs'


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def verified_file(row):
    path = ROOT / row['path']
    raw = path.read_bytes()
    if digest(raw) != row['sha256'] or len(raw) != row['bytes']:
        raise ValueError('Recorded source execution bytes changed: ' + row['path'])
    return raw


def build():
    raw = RECEIPT.read_bytes()
    receipt = json.loads(raw)
    if receipt['schema'] != 'MathScope.N6.SourceGateExecution/1':
        raise ValueError('Expected the observed N6 source gate receipt')
    gate = receipt['gate']
    if not (receipt['actualSourceConstructorExecuted'] is True
            and receipt['pass'] is True and gate['exitCode'] == 0
            and gate['testCount'] == gate['passCount'] and gate['failCount'] == 0):
        raise ValueError('The recorded source constructor did not pass every gate')
    verified_file(gate['log'])
    capture = json.loads(verified_file(receipt['sourceDependencyCapture']))
    files = capture['files']
    if len(files) != capture['fileCount']:
        raise ValueError('The captured source file count changed')
    for row in files:
        verified_file(row)
    aggregate = digest(json.dumps(files, sort_keys=True, separators=(',', ':')).encode())
    if aggregate != capture['aggregateSHA256']:
        raise ValueError('The original execution source manifest changed')
    artifacts = []
    for row in receipt['artifacts']:
        data = json.loads(verified_file(row))
        if data['schema'] != row['schema'] or data['graph'] != row['graph']:
            raise ValueError('An artifact graph binding changed: ' + row['path'])
        if any(check.get('pass') is not True for check in data['checks']):
            raise ValueError('An actual source check is not passing')
        if data['scope'].get('completeN6') is not False:
            raise ValueError('The finite constructor scope was enlarged')
        artifacts.append({**row, 'scope': data['scope'],
                          'checkCount': len(data['checks']),
                          'checks': [{'id': check.get('id', 'retained-exact-identity'),
                                      'pass': check['pass']}
                                     for check in data['checks']]})
    result = {
        'schema': 'MathScope.N6.RecordedSourceReconstruction/1',
        'status': 'RECORDED_SOURCE_EXECUTION_BYTE_VERIFIED',
        'recordedOnly': True,
        'freshSourceConstructorExecuted': False,
        'viewLabel': '저장된 실제 실행 자료 · 출처 검증',
        'receipt': {'path': str(RECEIPT.relative_to(ROOT)), 'sha256': digest(raw), 'bytes': len(raw)},
        'gate': gate,
        'sourceReferences': receipt['sourceReferences'],
        'sourceDependencyCapture': {**receipt['sourceDependencyCapture'],
                                    'fileCount': capture['fileCount'],
                                    'aggregateSHA256': capture['aggregateSHA256']},
        'artifacts': artifacts,
        'sourceValidation': {
            'mode': 'BUILD_TIME_BYTE_VERIFICATION',
            'allCapturedSourceFilesMatch': True,
            'allRecordedArtifactBytesMatch': True,
            'browserHasReexecutedConstructor': False,
            'replayMeaning': 'Recompute this recorded summary and its input/result/source hashes. The original source constructor is not rerun by browser replay.',
        },
        'retainedSourceLimits': receipt['retainedSourceLimits'],
        'remainingObligations': receipt['remainingObligations'],
        'historicalAttempts': receipt['historicalAttempts'],
        'checks': [
            {'id': 'recorded-source-constructor-gate-passed', 'pass': True, 'recordedOnly': True},
            {'id': 'captured-source-and-artifact-bytes-verified-at-build', 'pass': True, 'recordedOnly': True},
            {'id': 'no-fresh-constructor-or-complete-N6-claim', 'pass': True, 'recordedOnly': True},
        ],
        'completeN6': False,
        'initializedJ0': False,
        'analyticCertificate': None,
        'leanTheorem': None,
        'numericalFieldEnclosure': False,
    }
    header = '// Generated by tests/build-source-current-evidence.py from byte-verified actual execution receipts.\n'
    encoded = json.dumps(result, ensure_ascii=False, separators=(',', ':'))
    return header + 'const recorded = ' + encoded + ';\n' + '''
export function recordedSourceReconstruction(parameters={}){
  if(!parameters||typeof parameters!=='object'||Array.isArray(parameters)||Object.keys(parameters).length)
    throw Object.assign(new Error('The recorded source view takes no constructor parameters; its exact source and command are fixed by the execution receipt.'),{code:'INVALID_INPUT'});
  return JSON.parse(JSON.stringify(recorded));
}
'''


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = build()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != expected:
            raise ValueError('Recorded source view is stale; run this builder after reviewing the actual receipt')
    else:
        TARGET.write_text(expected)
    print(json.dumps({'pass': True, 'mode': 'check' if args.check else 'build',
                      'freshSourceConstructorExecuted': False,
                      'target': str(TARGET.relative_to(ROOT)),
                      'sha256': digest(expected.encode())}))


if __name__ == '__main__':
    main()
